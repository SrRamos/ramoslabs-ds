// @ramoslabs/css build (W1-201, ADR-009).
//
// Every `src/**/*.css` file is a component (or base) stylesheet. Nothing here is a hand-edited
// index: `dist/index.css` is generated from a glob, so adding a component file edits no shared file.
//
// Output:
//   dist/<path>.css   each source file, prefixed with the layer-order statement
//   dist/base.css     the files under src/base, in name order
//   dist/index.css    layer-order statement + base + every component, in name order
//
// Sources must keep every rule inside an `sj.*` layer so unlayered consumer CSS always wins.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

/** The layer order is part of the public API (ADR-009). Verbatim. */
export const LAYER_ORDER = '@layer sj.reset, sj.base, sj.component, sj.variant, sj.state;';
export const LAYER_NAMES = ['sj.reset', 'sj.base', 'sj.component', 'sj.variant', 'sj.state'];
const BANNER = '/* @ramoslabs/css. Generated by scripts/build.mjs; do not edit. */';

/** Top-level at-rules that cannot or need not live in a layer. */
const UNLAYERED_OK = new Set(['keyframes', 'property']);

/** Lists `.css` files under `dir`, sorted, skipping `_`-prefixed files and folders (templates). */
export function listSources(dir) {
  const out = [];
  const walk = (d) => {
    for (const entry of readdirSync(d, { withFileTypes: true }).sort((a, b) =>
      a.name < b.name ? -1 : a.name > b.name ? 1 : 0,
    )) {
      if (entry.name.startsWith('_')) continue;
      const p = join(d, entry.name);
      if (entry.isDirectory()) walk(p);
      else if (entry.name.endsWith('.css')) out.push(p);
    }
  };
  walk(dir);
  return out.map((p) => relative(dir, p).split(sep).join('/'));
}

/** Throws a descriptive error when a source file would break the layer contract. */
export function validateSource(name, css) {
  const root = postcss.parse(css, { from: name });
  for (const node of root.nodes) {
    if (node.type === 'comment') continue;
    const where = `${name}:${node.source?.start?.line ?? '?'}`;
    if (node.type !== 'atrule') {
      throw new Error(
        `${where}: top-level rule outside an sj.* layer. Wrap it in @layer sj.<layer> { }.`,
      );
    }
    if (node.name === 'import')
      throw new Error(`${where}: @import is not allowed in component CSS.`);
    if (node.name === 'layer') {
      const names = node.params.split(',').map((s) => s.trim());
      if (!node.nodes) throw new Error(`${where}: do not declare layer order in a component file.`);
      if (names.length !== 1 || !LAYER_NAMES.includes(names[0])) {
        throw new Error(
          `${where}: unknown layer "${node.params}". Allowed: ${LAYER_NAMES.join(', ')}.`,
        );
      }
      continue;
    }
    if (UNLAYERED_OK.has(node.name)) continue;
    throw new Error(`${where}: top-level @${node.name} outside an sj.* layer.`);
  }
}

/** Builds `outDir` from `srcDir`. Returns the list of emitted file names. */
export function buildCss({ srcDir, outDir }) {
  rmSync(outDir, { recursive: true, force: true });
  const sources = listSources(srcDir);
  const contents = new Map();
  for (const name of sources) {
    const css = readFileSync(join(srcDir, name), 'utf8');
    validateSource(name, css);
    contents.set(name, css.trim());
  }
  const emit = (name, body) => {
    const file = join(outDir, name);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, `${body.trim()}\n`);
  };
  const header = `${BANNER}\n${LAYER_ORDER}`;
  for (const [name, css] of contents) emit(name, `${header}\n\n${css}`);
  const isBase = (n) => n.startsWith('base/');
  const base = sources.filter(isBase);
  const components = sources.filter((n) => !isBase(n));
  emit('base.css', [header, ...base.map((n) => contents.get(n))].join('\n\n'));
  emit('index.css', [header, ...base, ...components].map((n) => contents.get(n) ?? n).join('\n\n'));
  return ['base.css', 'index.css', ...sources];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const files = buildCss({ srcDir: join(root, 'src'), outDir: join(root, 'dist') });
  console.log(`@ramoslabs/css: built ${files.length} files`);
}
