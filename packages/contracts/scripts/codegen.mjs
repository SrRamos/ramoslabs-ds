// Contract codegen (W1-304, ADR-010 "Consumers", ADR-004 "one types file", ADR-006/ADR-007).
// Library plus CLI.
//   node scripts/codegen.mjs           regenerate every file under packages/*/src/generated/
//   node scripts/codegen.mjs --check   regenerate in memory; exit 1 on any drift (clean-tree check)
// Output is pure data derived from `contracts/*.contract.json` and `kinds.contract.json`:
// deterministic (no clock, no fs listing order, prettier-formatted), so a second run is a no-op.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import { validateContract, validateKinds } from './validate.mjs';
import { atWording } from './at-wording.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const contractsRoot = resolve(here, '..');
export const repoRoot = resolve(contractsRoot, '..', '..');
const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));

export const ADAPTERS = ['react', 'vue', 'vanilla'];
const KINDS_FILE = 'kinds.contract.json';
const CODEGEN_REL = 'packages/contracts/scripts/codegen.mjs';

// ---------------------------------------------------------------- naming

/** `SJRadioGroup` -> { pascal: 'RadioGroup', camel: 'radioGroup', slug: 'radio-group' }. */
export function names(contractName) {
  const pascal = contractName.replace(/^SJ/, '');
  const camel = pascal[0].toLowerCase() + pascal.slice(1);
  const slug = pascal
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
  return { contract: contractName, pascal, camel, slug };
}
const upperFirst = (s) => s[0].toUpperCase() + s.slice(1);
const ident = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
const header = (source) =>
  `// GENERATED by ${CODEGEN_REL} from ${source}.\n// Do not edit: run \`bun run codegen\` and commit the result (contracts:check fails on drift).\n\n`;

// ---------------------------------------------------------------- kinds (ADR-007)

/**
 * Project one kinds.contract.json row onto the `Row` tuple the resolver consumes.
 * Row = [type(s), inputmode, autocomplete, enter, autocapitalize, autocorrect, spellcheck, gate?]
 */
export function kindRow(c) {
  const a = c.autocomplete;
  let ac;
  if (a.policy === 'omitted') ac = null;
  else if (a.policy === 'off') ac = 'off';
  else if (a.policy === 'context') ac = a.default ?? 'ctx';
  else {
    const toks = [...(a.tokens ?? []), ...(a.variants ?? [])];
    ac = a.policy === 'conditional' ? ['?', ...toks] : toks;
  }
  const cap = c.autocapitalize;
  const gate = c.kind === 'tax-id' ? [2] : c.group === 'postal-reference-account' ? [1] : [];
  return [
    c.type.length === 1 ? c.type[0] : c.type,
    c.inputmode,
    ac,
    c.enter === 'done' && c.enterAlternatives ? 'done/go' : c.enter,
    cap.value === 'characters' && cap.when ? 'characters?' : cap.value,
    c.autocorrect,
    c.spellcheck,
    ...gate,
  ];
}

function genKinds(kindsDoc) {
  const rows = kindsDoc.kinds;
  const body = rows.map((r) => `  ${ident(r.kind)}: ${JSON.stringify(kindRow(r))},`).join('\n');
  const union = rows.map((r) => `  | ${JSON.stringify(r.kind)}`).join('\n');
  const table = `${header(`packages/contracts/contracts/${KINDS_FILE}`)}// Typed kind table (ADR-007).
// Row = [type(s), inputmode, autocomplete, enter, autocapitalize, autocorrect, spellcheck, gate?]
//  autocomplete: null = attribute omitted | 'on' | 'off' | 'ctx' (consumer-supplied, else omitted)
//                | string[] tokens (first = default; 'x-*' = prefix family)
//                | ['?', ...tokens] emitted only when the context makes it meaningful.
//  enter: 'position' (form owner computes) | fixed hint | 'done/go' (OTP, by auto-submit).
//  autocapitalize 'characters?' = only when the canonical form is uppercase.
//  gate: 1 = inputmode only unless ctx.digits === false; 2 = inputmode only when ctx.digits === true.
export type Row = readonly [
  type: string | readonly string[],
  inputmode: string | null,
  autocomplete: string | null | readonly string[],
  enter: string,
  autocapitalize: string | null,
  autocorrect: 'on' | 'off' | null,
  spellcheck: boolean | null,
  gate?: 1 | 2,
];

/** The \`kind\` union: every ADR-007 kind, in contract order. An unknown kind is a type error. */
export type Kind =
${union};

export const KINDS = {
${body}
} as const satisfies Record<Kind, Row>;
`;
  return {
    'kinds/table.ts': table,
    'kinds/index.ts': `${header(`packages/contracts/contracts/${KINDS_FILE}`)}export { KINDS, type Kind, type Row } from './table';\n`,
  };
}

// ---------------------------------------------------------------- core: machine, keyboard, aria

/** Unique action ids in first-appearance order: the reducer's event names (S-CON gap 3). */
export const actionIds = (c) => [...new Set(c.actions.map((a) => a.id))];

function genCore(c) {
  const n = names(c.name);
  const src = `packages/contracts/contracts/${n.slug}.contract.json`;
  const states = c.state.machine;
  const events = actionIds(c);

  const transitions = Object.fromEntries(states.map((s) => [s, {}]));
  for (const a of c.actions) {
    const row = { to: a.to };
    if (a.emit !== undefined) row.emit = a.emit;
    if (a.focus !== undefined) row.focus = a.focus;
    transitions[a.from][a.id] = row;
  }
  const machine = `${header(src)}// ${c.name} finite-state table. \`initial\` is the first state of \`state.machine\`.
// An event with no row for the current state is a no-op (the reducer returns the state unchanged).
export const ${n.camel}Machine = {
  initial: ${JSON.stringify(states[0])},
  states: ${JSON.stringify(states)},
  events: ${JSON.stringify(events)},
  controllable: ${JSON.stringify(c.state.controllable)},
  transitions: ${JSON.stringify(transitions)},
} as const;

export type ${n.pascal}State = (typeof ${n.camel}Machine.states)[number];
export type ${n.pascal}Event = (typeof ${n.camel}Machine.events)[number];
`;

  const keyboard = `${header(src)}// ${c.name} keyboard map: anatomy part -> key -> action id (or movement word).
// One source for code and tests (ADR-006, ADR-010).
export const ${n.camel}Keyboard = ${JSON.stringify(c.keyboard)} as const;

export type ${n.pascal}KeyboardMap = typeof ${n.camel}Keyboard;
`;

  const parts = {};
  for (const p of c.anatomy) {
    const { part, ...rest } = p;
    parts[part] = rest;
  }
  const aria = {};
  for (const a of c.actions) {
    if (!a.aria && !a.dom) continue;
    aria[a.from] ??= {};
    const row = {};
    if (a.aria) row.aria = a.aria;
    if (a.dom) row.dom = a.dom;
    aria[a.from][a.id] = row;
  }
  const ariaFile = `${header(src)}// ${c.name} ARIA table: static anatomy (element, role, fixed attributes) and the attribute
// values each transition sets, keyed state -> event -> { aria?, dom? } per anatomy part.
// \`dom\` is for native state (for example \`checked\`) that must not be mirrored in ARIA.
export const ${n.camel}Aria = {
  parts: ${JSON.stringify(parts)},
  transitions: ${JSON.stringify(aria)},
} as const;
`;

  const atRows = c.a11y.atSupport.map((r) => ({ ...r, statement: atWording(r) }));
  const atFile = `${header(src)}// ${c.name} assistive-technology support, per AT and platform (ADR-010, ADR-015).
// \`test_status\` is copied from the contract; \`statement\` is the only wording docs may print for the row.
export const ${n.camel}AtSupport = ${JSON.stringify(atRows)} as const;
`;

  const index = `${header(src)}export * from './machine';\nexport * from './keyboard';\nexport * from './aria';\nexport * from './at-support';\n`;
  return {
    [`${n.slug}/machine.ts`]: machine,
    [`${n.slug}/keyboard.ts`]: keyboard,
    [`${n.slug}/aria.ts`]: ariaFile,
    [`${n.slug}/at-support.ts`]: atFile,
    [`${n.slug}/index.ts`]: index,
  };
}

// ---------------------------------------------------------------- adapters: types file (ADR-004)

const doc = (lines) => {
  const ls = lines.filter(Boolean);
  if (ls.length === 0) return '';
  return `  /** ${ls.join(' ')} */\n`;
};
// ADR-003 "Controlled/uncontrolled": the acceptance rule is the same for every controllable prop.
const CONTROLLED_RULE =
  'Controlled: the owner must accept (update this prop) synchronously inside the change callback; an owner that accepts later sees the native control snap back until its render commits.';
const propDocs = (p, controllable) =>
  doc([
    p.description,
    controllable.includes(p.name) ? CONTROLLED_RULE : '',
    p.default !== undefined ? `@default ${JSON.stringify(p.default)}` : '',
  ]);
const propLines = (c) =>
  c.props
    .map(
      (p) =>
        `${propDocs(p, c.state.controllable)}  ${ident(p.name)}${p.required ? '' : '?'}: ${p.type};`,
    )
    .join('\n');
const payloadTypes = (c) =>
  c.events
    .map((e) => `export type ${c.name}${upperFirst(e.name)}Payload = ${e.payload ?? 'void'};`)
    .join('\n');
const slotKey = (s) => (s.name === 'default' ? 'children' : s.name);

function genAdapterTypes(adapter, c) {
  const n = names(c.name);
  const src = `packages/contracts/contracts/${n.slug}.contract.json`;
  const P = (e) => `${c.name}${upperFirst(e.name)}Payload`;
  let out = `${header(src)}// ${c.name} types for @ramoslabs/${adapter}: props, events, slots (ADR-004 "one types file").\n`;
  out += `${payloadTypes(c)}\n\n`;
  if (adapter === 'react') {
    const handlers = c.events
      .map((e) => `  on${upperFirst(e.name)}?: (payload: ${P(e)}) => void;`)
      .join('\n');
    const slots = c.slots
      .map((s) => `${doc([s.description])}  ${ident(slotKey(s))}?: unknown;`)
      .join('\n');
    out += `export interface ${c.name}Props {\n${propLines(c)}\n${handlers}\n${slots}\n}\n`;
  } else if (adapter === 'vue') {
    const emits = c.events.map((e) => `  ${ident(e.name)}: [payload: ${P(e)}];`).join('\n');
    const slots = c.slots
      .map((s) => `${doc([s.description])}  ${ident(s.name)}?: () => unknown;`)
      .join('\n');
    out += `export interface ${c.name}Props {\n${propLines(c)}\n}\n\n`;
    out += `export interface ${c.name}Emits {\n${emits}\n}\n\n`;
    out += `export interface ${c.name}Slots {\n${slots}\n}\n`;
  } else {
    const handlers = c.events
      .map((e) => `  on${upperFirst(e.name)}?: (payload: ${P(e)}) => void;`)
      .join('\n');
    const detail = c.events.map((e) => `  ${ident(e.name)}: ${P(e)};`).join('\n');
    const slots = c.slots
      .map((s) => `${doc([s.description])}  ${ident(s.name)}?: string | Node;`)
      .join('\n');
    out += `export interface ${c.name}Options {\n${propLines(c)}\n${handlers}\n${slots}\n}\n\n`;
    out += `/** CustomEvent \`detail\` per event name. */\nexport interface ${c.name}EventDetail {\n${detail}\n}\n`;
  }
  return {
    [`${n.slug}/types.ts`]: out,
    [`${n.slug}/index.ts`]: `${header(src)}export * from './types';\n`,
  };
}

// ---------------------------------------------------------------- orchestration

/** Load and validate every contract. Throws on an invalid contract: codegen never emits from bad input. */
export function loadContracts(dir = join(contractsRoot, 'contracts')) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.contract.json'))
    .sort();
  const kinds = [];
  const components = [];
  for (const f of files) {
    const data = readJson(join(dir, f));
    if (f === KINDS_FILE) {
      const r = validateKinds(data);
      if (!r.valid) throw new Error(`${f}: ${JSON.stringify(r.errors)}`);
      kinds.push(data);
    } else {
      const r = validateContract(data);
      if (!r.valid) throw new Error(`${f}: ${JSON.stringify(r.errors)}`);
      components.push(data);
    }
  }
  return { kinds: kinds[0] ?? null, components };
}

async function format(path, code) {
  const config = (await prettier.resolveConfig(join(repoRoot, path))) ?? {};
  return prettier.format(code, { ...config, filepath: join(repoRoot, path) });
}

/**
 * Generate every file as { 'packages/<pkg>/src/generated/<...>': content } (repo-relative paths,
 * sorted). Pure: no writes.
 */
export async function generate({ contractsDir } = {}) {
  const { kinds, components } = loadContracts(contractsDir);
  const raw = {};
  const barrels = { core: [] };
  for (const a of ADAPTERS) barrels[a] = [];
  const put = (pkg, files) => {
    for (const [rel, code] of Object.entries(files))
      raw[`packages/${pkg}/src/generated/${rel}`] = code;
  };
  if (kinds) {
    put('core', genKinds(kinds));
    barrels.core.push('kinds');
  }
  for (const c of components) {
    const slug = names(c.name).slug;
    put('core', genCore(c));
    barrels.core.push(slug);
    for (const a of ADAPTERS) {
      put(a, genAdapterTypes(a, c));
      barrels[a].push(slug);
    }
  }
  for (const [pkg, mods] of Object.entries(barrels)) {
    const sorted = [...mods].sort();
    raw[`packages/${pkg}/src/generated/index.ts`] =
      `${header('packages/contracts/contracts/*.contract.json')}${
        sorted.length
          ? sorted.map((m) => `export * from './${m}/index';`).join('\n') + '\n'
          : 'export {};\n'
      }`;
  }
  const out = {};
  for (const path of Object.keys(raw).sort()) out[path] = await format(path, raw[path]);
  return out;
}

const generatedDirs = () =>
  ['core', ...ADAPTERS].map((p) => join(repoRoot, 'packages', p, 'src', 'generated'));

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...listFiles(p));
    else out.push(p);
  }
  return out;
}

/** Compare generated output with the working tree. Returns drift entries (empty = clean). */
export async function checkDrift({ contractsDir } = {}) {
  const gen = await generate({ contractsDir });
  const drift = [];
  for (const [path, code] of Object.entries(gen)) {
    const abs = join(repoRoot, path);
    if (!existsSync(abs)) drift.push({ path, problem: 'missing' });
    else if (readFileSync(abs, 'utf8') !== code) drift.push({ path, problem: 'differs' });
  }
  for (const dir of generatedDirs())
    for (const f of listFiles(dir)) {
      const rel = relative(repoRoot, f).split('\\').join('/');
      if (!(rel in gen)) drift.push({ path: rel, problem: 'stale (no contract produces it)' });
    }
  return drift;
}

/** Write the generated tree; removes stale files so the directories are exactly the output. */
export async function writeGenerated({ contractsDir } = {}) {
  const gen = await generate({ contractsDir });
  for (const dir of generatedDirs()) rmSync(dir, { recursive: true, force: true });
  for (const [path, code] of Object.entries(gen)) {
    const abs = join(repoRoot, path);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, code);
  }
  return Object.keys(gen);
}

// ---------------------------------------------------------------- reducer equivalence (ADR-010)

/**
 * Reducer events must equal the contract `actions` ids (set equality). When a `reduce(state, event)`
 * function is supplied, every contract row must also hold: reduce(from, id) === to, and any
 * (state, event) pair without a row must leave the state unchanged.
 * @returns {string[]} problems (empty = equivalent)
 */
export function checkReducerEquivalence(contract, { reducerEvents, reduce } = {}) {
  const problems = [];
  if (!Array.isArray(reducerEvents)) {
    return [`${contract.name}: reducer does not export \`reducerEvents\` (string[])`];
  }
  const want = new Set(actionIds(contract));
  const have = new Set(reducerEvents);
  for (const id of want)
    if (!have.has(id))
      problems.push(`${contract.name}: contract action "${id}" has no reducer event`);
  for (const id of have)
    if (!want.has(id))
      problems.push(`${contract.name}: reducer event "${id}" is not a contract action`);
  if (typeof reduce === 'function') {
    const rows = new Map(contract.actions.map((a) => [`${a.from}\u0000${a.id}`, a.to]));
    for (const s of contract.state.machine)
      for (const id of want) {
        const expected = rows.get(`${s}\u0000${id}`) ?? s;
        const got = reduce(s, { type: id });
        if (got !== expected)
          problems.push(
            `${contract.name}: reduce("${s}", "${id}") returned "${got}", contract says "${expected}"`,
          );
      }
  }
  return problems;
}

// ---------------------------------------------------------------- CLI

const isCli = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) {
  const check = process.argv.includes('--check');
  try {
    if (check) {
      const drift = await checkDrift();
      if (drift.length) {
        for (const d of drift) console.error(`codegen: ${d.path}: ${d.problem}`);
        console.error('codegen: generated files drifted. Run `bun run codegen` and commit.');
        process.exit(1);
      }
      console.log('codegen: generated files are up to date');
    } else {
      const files = await writeGenerated();
      console.log(`codegen: wrote ${files.length} files`);
    }
  } catch (e) {
    console.error(`codegen: ${e.message}`);
    process.exit(1);
  }
}
