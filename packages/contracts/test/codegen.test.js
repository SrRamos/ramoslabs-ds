import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { describe, expect, it } from 'vitest';
import {
  ADAPTERS,
  actionIds,
  checkDrift,
  checkReducerEquivalence,
  contractsRoot,
  generate,
  loadContracts,
  names,
  repoRoot,
} from '../scripts/codegen.mjs';
import * as fixtureReducer from './fixtures/reducer/toggle.reducer.js';

const fixture = JSON.parse(
  readFileSync(new URL('./fixtures/reducer/toggle.contract.json', import.meta.url), 'utf8'),
);
const cli = join(contractsRoot, 'scripts', 'codegen.mjs');

describe('names', () => {
  it('derives pascal, camel and slug', () => {
    expect(names('SJRadioGroup')).toEqual({
      contract: 'SJRadioGroup',
      pascal: 'RadioGroup',
      camel: 'radioGroup',
      slug: 'radio-group',
    });
    expect(names('SJButton').slug).toBe('button');
  });
});

describe('generated files are in sync (drift fails the gate)', () => {
  it('regenerating produces no diff', async () => {
    expect(await checkDrift()).toEqual([]);
  });
  it('is deterministic', async () => {
    expect(await generate()).toEqual(await generate());
  });
  it('a seeded contract change is reported as drift', async () => {
    const { mkdtempSync, copyFileSync, readdirSync, writeFileSync } = await import('node:fs');
    const { tmpdir } = await import('node:os');
    const dir = mkdtempSync(join(tmpdir(), 'codegen-'));
    const src = join(contractsRoot, 'contracts');
    for (const f of readdirSync(src)) copyFileSync(join(src, f), join(dir, f));
    const p = join(dir, 'button.contract.json');
    const c = JSON.parse(readFileSync(p, 'utf8'));
    c.keyboard.root.Escape = 'press';
    writeFileSync(p, JSON.stringify(c));
    const drift = await checkDrift({ contractsDir: dir });
    expect(drift.map((d) => d.path)).toContain('packages/core/src/generated/button/keyboard.ts');
  });
  it('a stale or missing generated file is reported', async () => {
    const { mkdtempSync, copyFileSync, readdirSync } = await import('node:fs');
    const { tmpdir } = await import('node:os');
    const dir = mkdtempSync(join(tmpdir(), 'codegen-'));
    const src = join(contractsRoot, 'contracts');
    for (const f of readdirSync(src))
      if (f !== 'switch.contract.json') copyFileSync(join(src, f), join(dir, f));
    const problems = (await checkDrift({ contractsDir: dir })).map((d) => d.problem);
    expect(problems.some((p) => p.startsWith('stale'))).toBe(true);
  });
  it('--check exits 0 on a clean tree', () => {
    const r = spawnSync(process.execPath, [cli, '--check'], { encoding: 'utf8' });
    expect(r.status).toBe(0);
  });
});

describe('output shape', () => {
  it('emits core machine/keyboard/aria and adapter types for every contract, plus kinds and barrels', async () => {
    const out = await generate();
    const { components } = loadContracts();
    for (const c of components) {
      const { slug } = names(c.name);
      for (const f of ['machine', 'keyboard', 'aria', 'at-support', 'index'])
        expect(out).toHaveProperty([`packages/core/src/generated/${slug}/${f}.ts`]);
      for (const a of ADAPTERS)
        expect(out).toHaveProperty([`packages/${a}/src/generated/${slug}/types.ts`]);
    }
    expect(out).toHaveProperty(['packages/core/src/generated/kinds/table.ts']);
    for (const p of ['core', ...ADAPTERS])
      expect(out[`packages/${p}/src/generated/index.ts`]).toContain('GENERATED');
  });
  it('every file carries the generated header', async () => {
    for (const code of Object.values(await generate())) expect(code).toMatch(/^\/\/ GENERATED by /);
  });
});

describe('reducer events == contract actions (ADR-010 equivalence check)', () => {
  it('fixture contract and reducer are equivalent', () => {
    expect(checkReducerEquivalence(fixture, fixtureReducer)).toEqual([]);
  });
  it('action ids are the unique event names (a toggle is two rows, one event)', () => {
    expect(actionIds(fixture)).toEqual(['toggle', 'reset']);
  });
  it('seeded: a reducer event missing from the contract fails', () => {
    const p = checkReducerEquivalence(fixture, {
      ...fixtureReducer,
      reducerEvents: ['toggle', 'reset', 'extra'],
    });
    expect(p).toEqual([expect.stringContaining('"extra" is not a contract action')]);
  });
  it('seeded: a contract action the reducer lacks fails', () => {
    const p = checkReducerEquivalence(fixture, { ...fixtureReducer, reducerEvents: ['toggle'] });
    expect(p).toEqual([expect.stringContaining('"reset" has no reducer event')]);
  });
  it('seeded: a wrong transition fails', () => {
    const reduce = (s, e) => (e.type === 'reset' ? 'on' : fixtureReducer.reduce(s, e));
    const p = checkReducerEquivalence(fixture, {
      reducerEvents: fixtureReducer.reducerEvents,
      reduce,
    });
    expect(p.some((x) => x.includes('reduce("on", "reset")'))).toBe(true);
  });
  it('seeded: an unlisted (state, event) pair that moves state fails', () => {
    const reduce = (s, e) =>
      e.type === 'reset' && s === 'off' ? 'on' : fixtureReducer.reduce(s, e);
    const p = checkReducerEquivalence(fixture, {
      reducerEvents: fixtureReducer.reducerEvents,
      reduce,
    });
    expect(p.some((x) => x.includes('reduce("off", "reset")'))).toBe(true);
  });
  it('a reducer without reducerEvents fails', () => {
    expect(checkReducerEquivalence(fixture, {})[0]).toContain('reducerEvents');
  });
});

// Runs automatically for every component that gains a reducer. Convention: the reducer module is
// packages/core/src/<slug>/reducer.ts and exports `reducerEvents` (string[]) and, optionally,
// `reduce(state, { type })`. Button and switch have none yet, so they are reported as pending.
describe('real component reducers', () => {
  const { components } = loadContracts();
  for (const c of components) {
    const { slug } = names(c.name);
    const file = join(repoRoot, 'packages', 'core', 'src', slug, 'reducer.ts');
    if (!existsSync(file)) {
      // #47 owner: SrRamos. A contract without a reducer module is a visible skip until its stream lands.
      it.skip(`${c.name}: no reducer yet (packages/core/src/${slug}/reducer.ts)`, () => {});
      continue;
    }
    it(`${c.name}: reducer events equal contract actions`, async () => {
      const mod = await import(file);
      expect(checkReducerEquivalence(c, mod)).toEqual([]);
    });
  }
});
