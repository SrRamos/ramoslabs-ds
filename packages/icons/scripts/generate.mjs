// @ts-check
// Codegen for @ramoslabs/icons (ADR-016). Reads the exact-pinned `lucide-static` devDependency and
// `src/icons.list.json`, emits one module per icon, the barrel, the name tables and the notices file.
// `--check` regenerates in memory and fails on any byte of the committed output not derived from
// the pinned upstream (provenance), including stray files.
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const packageDir = resolve(here, '..');

const NAME = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

/** @param {string} kebab */
export const pascal = (kebab) =>
  kebab
    .split('-')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');

/**
 * Read the pinned upstream package.
 * @param {string} pkgDir
 */
export function loadUpstream(pkgDir) {
  const require = createRequire(join(pkgDir, 'package.json'));
  const upPkgPath = require.resolve('lucide-static/package.json');
  const upDir = dirname(upPkgPath);
  const version = JSON.parse(readFileSync(upPkgPath, 'utf8')).version;
  const own = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
  const pinned = own.devDependencies?.['lucide-static'];
  if (typeof pinned !== 'string' || !/^\d+\.\d+\.\d+$/.test(pinned)) {
    throw new Error(`lucide-static must be an exact-pinned devDependency, got ${pinned}`);
  }
  if (pinned !== version) {
    throw new Error(`installed lucide-static ${version} differs from the pinned ${pinned}`);
  }
  /** @type {Record<string, [string, Record<string, string>][]>} */
  const nodes = JSON.parse(readFileSync(join(upDir, 'icon-nodes.json'), 'utf8'));
  const license = readFileSync(join(upDir, 'LICENSE'), 'utf8');
  // Upstream re-export table: `export { default as A, default as B } from './icons/x.mjs';`
  /** @type {Map<string, string>} PascalCase export name -> canonical file stem */
  const reexports = new Map();
  const table = readFileSync(join(upDir, 'dist/esm/lucide-static.mjs'), 'utf8');
  for (const m of table.matchAll(/^export \{([^}]*)\} from '\.\/icons\/([^']+)\.mjs';$/gm)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().replace(/^default as /, '');
      reexports.set(name, m[2]);
    }
  }
  return { version, nodes, license, reexports };
}

/**
 * @param {string} pkgDir
 * @param {ReturnType<typeof loadUpstream>} upstream
 */
export function loadList(pkgDir, upstream) {
  const list = JSON.parse(readFileSync(join(pkgDir, 'src/icons.list.json'), 'utf8'));
  /** @type {{ name: string, mirror?: true, aliases?: string[], group?: string }[]} */
  const icons = list.icons;
  const seen = new Set();
  for (const icon of icons) {
    if (!NAME.test(icon.name)) throw new Error(`invalid icon name "${icon.name}"`);
    if (seen.has(icon.name)) throw new Error(`duplicate icon "${icon.name}"`);
    seen.add(icon.name);
    if (!Object.hasOwn(upstream.nodes, icon.name)) {
      throw new Error(
        `icon "${icon.name}" is not a canonical entry of lucide-static ${upstream.version}`,
      );
    }
    if (icon.mirror !== undefined && icon.mirror !== true) {
      throw new Error(`icon "${icon.name}": mirror must be true or absent`);
    }
  }
  const aliasOwner = new Map();
  for (const icon of icons) {
    for (const alias of icon.aliases ?? []) {
      if (!NAME.test(alias)) throw new Error(`invalid alias "${alias}"`);
      if (seen.has(alias)) throw new Error(`alias "${alias}" collides with a canonical icon name`);
      if (aliasOwner.has(alias)) throw new Error(`duplicate alias "${alias}"`);
      aliasOwner.set(alias, icon.name);
      const upstreamTarget = upstream.reexports.get(pascal(alias));
      if (upstreamTarget !== icon.name) {
        throw new Error(
          `alias "${alias}" -> "${icon.name}" is wrong: upstream ${upstream.version} maps "${alias}" to ${
            upstreamTarget === undefined ? 'nothing' : `"${upstreamTarget}"`
          }`,
        );
      }
    }
  }
  return { icons, source: String(list.$source ?? '') };
}

/**
 * Compute every generated file as `relative path -> content`. Pure; no writes.
 * @param {string} [pkgDir]
 * @returns {Map<string, string>}
 */
export function buildOutputs(pkgDir = packageDir) {
  const upstream = loadUpstream(pkgDir);
  const { icons } = loadList(pkgDir, upstream);
  const banner = `/** @license lucide-static v${upstream.version} ISC. Lucide Contributors; Feather icons MIT, Cole Bemis. See THIRD-PARTY-NOTICES.md */`;
  const header = '// Generated by scripts/generate.mjs from icons.list.json. Do not edit.';
  /** @type {Map<string, string>} */
  const out = new Map();

  for (const icon of icons) {
    const id = pascal(icon.name);
    const nodes = upstream.nodes[icon.name].map(([tag, attrs]) => [tag, { ...attrs }]);
    const lines = [
      `import type { IconData } from '../../types.js';`,
      '',
      banner,
      `export const ${id}: IconData = {`,
      `  name: ${JSON.stringify(icon.name)},`,
      `  nodes: ${JSON.stringify(nodes)},`,
    ];
    if (icon.mirror) lines.push('  mirror: true,');
    lines.push('};', `export { ${id} as ${id}Icon };`, '');
    out.set(`src/generated/icons/${icon.name}.ts`, lines.join('\n'));
  }

  out.set(
    'src/generated/index.ts',
    [
      header,
      ...icons.map((i) => {
        const id = pascal(i.name);
        return `export { ${id}, ${id}Icon } from './icons/${i.name}.js';`;
      }),
      '',
    ].join('\n'),
  );

  const aliases = icons.flatMap((i) => (i.aliases ?? []).map((a) => [a, i.name]));
  out.set(
    'src/generated/all.ts',
    [
      header,
      `import type { IconData } from '../types.js';`,
      ...icons.map((i) => `import { ${pascal(i.name)} } from './icons/${i.name}.js';`),
      '',
      '/** Every icon by canonical name. */',
      'export const icons: Readonly<Record<string, IconData>> = {',
      ...icons.map((i) => `  ${JSON.stringify(i.name)}: ${pascal(i.name)},`),
      '};',
      '',
      '/** Legacy alias to canonical name, validated against the pinned upstream re-export table. */',
      'export const aliases: Readonly<Record<string, string>> = {',
      ...aliases.map(([a, n]) => `  ${JSON.stringify(a)}: ${JSON.stringify(n)},`),
      '};',
      '',
    ].join('\n'),
  );

  out.set(
    'THIRD-PARTY-NOTICES.md',
    [
      '# Third-party notices',
      '',
      '<!-- Generated by scripts/generate.mjs from the pinned lucide-static LICENSE. Do not edit. -->',
      '',
      `The glyph data in @ramoslabs/icons is derived from lucide-static v${upstream.version}`,
      '(https://lucide.dev), which is distributed under the ISC License. Some Lucide icons are derived',
      'from Feather (MIT). The upstream licence text follows verbatim.',
      '',
      '---',
      '',
      upstream.license.trimEnd(),
      '',
    ].join('\n'),
  );
  return out;
}

/** @param {string} dir @returns {string[]} files relative to `dir`, posix separators */
function walk(dir) {
  /** @type {string[]} */
  const files = [];
  if (!existsSync(dir)) return files;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(p).map((f) => `${entry.name}/${f}`));
    else files.push(entry.name);
  }
  return files;
}

/**
 * Compare committed output to a fresh derivation. Returns a list of problems (empty when clean).
 * @param {string} [pkgDir]
 */
export function checkOutputs(pkgDir = packageDir) {
  const expected = buildOutputs(pkgDir);
  /** @type {string[]} */
  const problems = [];
  for (const [path, content] of expected) {
    const file = join(pkgDir, path);
    if (!existsSync(file)) problems.push(`missing: ${path}`);
    else if (readFileSync(file, 'utf8') !== content)
      problems.push(`differs from upstream: ${path}`);
  }
  const have = walk(join(pkgDir, 'src/generated')).map((f) => `src/generated/${f}`);
  for (const f of have) if (!expected.has(f)) problems.push(`unexpected file: ${f}`);
  return problems;
}

/** @param {string} [pkgDir] */
export function writeOutputs(pkgDir = packageDir) {
  const expected = buildOutputs(pkgDir);
  rmSync(join(pkgDir, 'src/generated'), { recursive: true, force: true });
  for (const [path, content] of expected) {
    const file = join(pkgDir, path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
  return expected.size;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.includes('--check')) {
      const problems = checkOutputs();
      if (problems.length) {
        console.error(
          `icons:check failed (${problems.length}):\n  ${problems.slice(0, 20).join('\n  ')}`,
        );
        console.error('Run `bun run --filter @ramoslabs/icons generate` and review the diff.');
        process.exit(1);
      }
      console.log('icons:check ok');
    } else {
      console.log(
        `generated ${writeOutputs()} files (${relative(process.cwd(), packageDir) || '.'})`,
      );
    }
  } catch (e) {
    console.error(`icons: ${e instanceof Error ? e.message : e}`);
    process.exit(1);
  }
}
